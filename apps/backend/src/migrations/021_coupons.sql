CREATE TABLE IF NOT EXISTS coupons (
  id text PRIMARY KEY,
  code text NOT NULL UNIQUE,
  generated boolean NOT NULL DEFAULT true,
  store_id text NOT NULL REFERENCES stores(id),
  all_franchise_stores boolean NOT NULL DEFAULT false,
  percent boolean NOT NULL DEFAULT false,
  amount integer NOT NULL CHECK (amount >= 0),
  value_limit_cents integer CHECK (value_limit_cents IS NULL OR value_limit_cents >= 0),
  usage_limit integer CHECK (usage_limit IS NULL OR usage_limit >= 0),
  valid_from text,
  valid_to text,
  restrict_hours boolean NOT NULL DEFAULT false,
  hour_start text,
  hour_end text,
  restrict_weekday boolean NOT NULL DEFAULT false,
  weekday integer CHECK (weekday IS NULL OR weekday BETWEEN 0 AND 6),
  weekday_value_limit_cents integer,
  weekday_usage_limit integer,
  restrict_store boolean NOT NULL DEFAULT false,
  restrict_store_id text REFERENCES stores(id),
  store_value_limit_cents integer,
  store_usage_limit integer,
  restrict_customer boolean NOT NULL DEFAULT false,
  customer_id text REFERENCES customers(id),
  customer_value_limit_cents integer,
  customer_usage_limit integer,
  restrict_service boolean NOT NULL DEFAULT false,
  service text CHECK (service IS NULL OR service IN ('WASHER', 'DRYER')),
  service_value_limit_cents integer,
  service_usage_limit integer,
  birthday boolean NOT NULL DEFAULT false,
  first_purchase boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
